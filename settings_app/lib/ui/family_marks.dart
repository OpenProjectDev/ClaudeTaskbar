// The family's other two marks, for About beside this app's own, as the
// OpenProject apps draw them (OpenFinances' lib/app/family_marks.dart):
// OpenDesign (a ruler and pencil: Flaticon, Arkinasi) and
// OpenProject (a circuit brain: Flaticon, gravisio), both credited on the
// Licenses screen and in ICONS.md. The glyph on a 1024 grid on the family's
// rounded plate (corners 22% of the edge, #303237), the glyph white. Outlines
// in source are how these marks ship: no icon files (ICONS.md).

import 'package:flutter/widgets.dart';

/// The plate the family's marks sit on.
const Color kBrandPlate = Color(0xFF303237);

/// Which family mark.
enum FamilyMark { openDesign, openProject }

/// [mark] at [size]: its white glyph on the rounded plate.
class FamilyMarkView extends StatelessWidget {
  const FamilyMarkView(this.mark, {super.key, required this.size});
  final FamilyMark mark;
  final double size;

  @override
  Widget build(BuildContext context) => CustomPaint(size: Size.square(size), painter: _FamilyPainter(mark));
}

class _FamilyPainter extends CustomPainter {
  const _FamilyPainter(this.mark);
  final FamilyMark mark;

  static final _glyphs = {
    FamilyMark.openDesign: svgPath(_openDesign, evenOdd: true),
    FamilyMark.openProject: svgPath(_openProject, evenOdd: true),
  };

  @override
  void paint(Canvas canvas, Size size) {
    canvas.scale(size.width / 1024);
    canvas.drawRRect(
      RRect.fromLTRBR(0, 0, 1024, 1024, const Radius.circular(225)),
      Paint()..color = kBrandPlate,
    );
    canvas.drawPath(_glyphs[mark]!, Paint()..color = const Color(0xFFFFFFFF));
  }

  @override
  bool shouldRepaint(_FamilyPainter old) => old.mark != mark;
}

/// SVG path data [d] (absolute M, L, C, S, Z; a command's numbers may
/// repeat without it) as a [Path]; [evenOdd]: holes where shapes overlap.
Path svgPath(String d, {bool evenOdd = false}) {
  final t = RegExp(
    r'[MLCSZ]|-?\d*\.?\d+(?:e-?\d+)?',
  ).allMatches(d).map((m) => m.group(0)!).toList();
  final p = Path()
    ..fillType = evenOdd ? PathFillType.evenOdd : PathFillType.nonZero;
  var i = 0;
  var cmd = 'M';
  // The last point and the last curve's second control point (for S).
  var x = 0.0, y = 0.0, cx = 0.0, cy = 0.0;
  double n() => double.parse(t[i++]);
  while (i < t.length) {
    if (RegExp(r'^[MLCSZ]$').hasMatch(t[i])) cmd = t[i++];
    switch (cmd) {
      case 'M':
        p.moveTo(x = n(), y = n());
        cx = x;
        cy = y;
        cmd = 'L'; // numbers after an M's pair are lines
      case 'L':
        p.lineTo(x = n(), y = n());
        cx = x;
        cy = y;
      case 'C':
        final (x1, y1, x2, y2) = (n(), n(), n(), n());
        p.cubicTo(x1, y1, x2, y2, x = n(), y = n());
        cx = x2;
        cy = y2;
      case 'S':
        // Its first control point mirrors the last curve's second.
        final (x1, y1) = (2 * x - cx, 2 * y - cy);
        final (x2, y2) = (n(), n());
        p.cubicTo(x1, y1, x2, y2, x = n(), y = n());
        cx = x2;
        cy = y2;
      case 'Z':
        p.close();
        cx = x;
        cy = y;
        // A Z with nothing after it: done; numbers after it would be an
        // error in the data.
        if (i < t.length && !RegExp(r'^[MLCSZ]$').hasMatch(t[i])) i++;
    }
  }
  return p;
}

